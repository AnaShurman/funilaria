-- Create clientes table (using existing column names)
CREATE TABLE IF NOT EXISTS clientes (
  id int8 PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
  created_at timestamptz DEFAULT now(),
  cliente_nome text NOT NULL,
  cliente_telefone text,
  cliente_email text,
  cliente_cpf text
);

-- Create veiculos table (using existing column names)
CREATE TABLE IF NOT EXISTS veiculos (
  id int8 PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
  created_at timestamptz DEFAULT now(),
  cliente_id int8 REFERENCES clientes(id) ON DELETE CASCADE,
  veiculo_placa text NOT NULL,
  veiculo_modelo text,
  veiculo_marca text,
  veiculo_cor text,
  veiculo_ano text
);

-- Update orcamentos table to reference clientes and veiculos
ALTER TABLE orcamentos
  ADD COLUMN IF NOT EXISTS cliente_id uuid REFERENCES clientes(id) ON DELETE SET NULL,
  ADD COLUMN IF NOT EXISTS veiculo_id uuid REFERENCES veiculos(id) ON DELETE SET NULL;

-- Create indexes for better performance
CREATE INDEX IF NOT EXISTS idx_clientes_nome ON clientes(cliente_nome);
CREATE INDEX IF NOT EXISTS idx_clientes_telefone ON clientes(cliente_telefone);
CREATE INDEX IF NOT EXISTS idx_veiculos_placa ON veiculos(veiculo_placa);
CREATE INDEX IF NOT EXISTS idx_veiculos_cliente_id ON veiculos(cliente_id);
CREATE INDEX IF NOT EXISTS idx_orcamentos_cliente_id ON orcamentos(cliente_id);
CREATE INDEX IF NOT EXISTS idx_orcamentos_veiculo_id ON orcamentos(veiculo_id);

-- Add unique constraint on placa
CREATE UNIQUE INDEX IF NOT EXISTS idx_veiculos_placa_unique ON veiculos(veiculo_placa);

